/**
 * Refreshes the bundled TTAO adjudicator snapshot (PRD #202). Run by hand, then commit
 * the result and deploy: npm run refresh:ttao
 *
 * The app never calls TTAO itself. Their endpoint is undocumented and only allows
 * requests from TTAO's own origin, so this script is the only thing that touches it,
 * and it is not part of the build. Only name, city, and nearest ESC are kept; bios and
 * every other field in the response are dropped here.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://connect.ttao.org/users/list/search?page=1&count=10000&sort=lastName%2CfirstName&roles=15&current=true';
const OUTPUT = fileURLToPath(new URL('../src/model/ttaoRosterSnapshot.ts', import.meta.url));

const tidy = (text) => (text ?? '').trim().replace(/\s+/g, ' ');

const response = await fetch(SOURCE, { headers: { accept: 'application/json' } });
if (!response.ok) throw new Error(`TTAO answered ${response.status}; snapshot left as it is.`);
const rows = await response.json();

const judges = (Array.isArray(rows) ? rows : [])
  .map((row) => ({
    sortKey: `${tidy(row.lastName)} ${tidy(row.firstName)}`.toLowerCase(),
    // Some names carry pronouns, like "(he/him/his)". Those shouldn't reach a judge slot or a document.
    name: tidy(`${row.firstName ?? ''} ${row.lastName ?? ''}`.replace(/\((he|she|they)\/[^)]*\)/gi, '')),
    city: tidy(row.city),
    esc: tidy(row.nearestEsc),
  }))
  .filter((judge) => judge.name)
  .sort((a, b) => (a.sortKey < b.sortKey ? -1 : a.sortKey > b.sortKey ? 1 : 0));

// An empty answer means the endpoint changed, not that TTAO has no judges.
if (judges.length === 0) throw new Error('TTAO returned no judges; snapshot left as it is.');

const asOf = new Date().toISOString().slice(0, 10);
const lines = judges.map(({ name, city, esc }) => `    ${JSON.stringify({ name, city, esc })},`);

writeFileSync(
  OUTPUT,
  `// Generated by scripts/refresh-ttao-roster.mjs. Don't edit by hand.
import type { RosterSnapshot } from './ttaoRoster';

export const TTAO_SNAPSHOT: RosterSnapshot = {
  asOf: ${JSON.stringify(asOf)},
  judges: [
${lines.join('\n')}
  ],
};
`,
);
console.log(`Wrote ${judges.length} judges as of ${asOf} to ${OUTPUT}`);
